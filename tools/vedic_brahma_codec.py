def decode_vedic_brahma_chunk(text):
    """Decodes a VedicBrahma2 raw ASCII string to pure Unicode Devanagari."""
    if not text:
        return ""
    
    t = text
    t = re.sub(r'^[\x00-\x1f\s]+', '', t.strip())
    t = re.sub(r'^[0-9A-Fa-f\x00\s]+[,ए]?\s*', '', t)
    t = re.sub(r'0000[0-9A-Fa-f\x00\s]+[,ए]?\s*', '', t)
    t = re.sub(r'^[\x00-\x1f\s]+', '', t)
    
    # Pre-substitutions
    for k, v in EXACT_WORD_MAP:
        t = t.replace(k, v)
        
    from krutidev_decoder import krutidev_to_devanagari
    t = krutidev_to_devanagari(t)
    
    # Post-substitutions
    for k, v in POST_CLEAN_MAP:
        t = t.replace(k, v)
        
    # Final cleanup
    t = t.replace('\r\n', '\n').replace('\r', '\n')
    t = re.sub(r'[\x00-\x09\x0b\x0c\x0e-\x1f]', '', t)
    t = re.sub(r'संस्व([तते])', r'संस्कृ\1', t)
    t = re.sub(r'\bवत्वा\b', 'कृत्वा', t)
    t = re.sub(r'\bपवत्वा\b', 'प्रकृत्या', t)
    t = re.sub(r'\bवते\b', 'कृते', t)
    t = re.sub(r'\bवतम्\b', 'कृतम्', t)
    t = re.sub(r'\bवतमेव\b', 'कृतमेव', t)
    t = re.sub(r'\bवतं\b', 'कृतं', t)
    t = re.sub(r'\bवतः\b', 'कृतः', t)
    t = re.sub(r'\bअपञ्चीवत', 'अपञ्चीकृत', t)
    t = re.sub(r' +', ' ', t)
    t = re.sub(r' ।+', ' ।', t)
    t = re.sub(r' ॥+', ' ॥', t)
    t = re.sub(r'\n{3,}', '\n\n', t)
    
    return t.strip()
