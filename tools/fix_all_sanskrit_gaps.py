def clean_text(text):
    t = text
    for pat, repl in REPLACEMENTS:
        if callable(repl):
            t = re.sub(pat, repl, t)
        else:
            t = re.sub(pat, repl, t)
    # clean multiple spaces
    t = re.sub(r' +', ' ', t)
    t = re.sub(r' :+', ':', t)
    t = re.sub(r':+:', ':', t)
    t = re.sub(r'\n{3,}', '\n\n', t)
    return t.strip()

